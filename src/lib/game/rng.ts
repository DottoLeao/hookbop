/** FNV-1a, 32 bits, over the UTF-16 code units of the text. */
function fnv1a(text: string): number {
  let hash = 0x811c9dc5;
  for (let i = 0; i < text.length; i++) {
    hash ^= text.charCodeAt(i);
    hash = Math.imul(hash, 0x01000193);
  }
  return hash >>> 0;
}

/** mulberry32: a small generator that gives numbers from 0 up to but not including 1. */
function mulberry32(state: number): () => number {
  let a = state >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = Math.imul(a ^ (a >>> 15), a | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/**
 * A random number generator that always gives the same sequence for the same seed
 * (mulberry32 over the FNV-1a hash of the seed), so a song gets the same blanks every time.
 */
export function seededRng(seed: string): () => number {
  return mulberry32(fnv1a(seed));
}

/** The items in a random order taken from `rng` (Fisher-Yates). The input is not changed. */
export function shuffled<T>(items: readonly T[], rng: () => number): T[] {
  const out = [...items];
  for (let i = out.length - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1));
    [out[i], out[j]] = [out[j], out[i]];
  }
  return out;
}
